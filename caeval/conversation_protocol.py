"""Stateless full-history patient conversation endpoint contract.

Episode and request nonces are randomly generated by the evaluator. They
contain no case identifiers, hidden world facts, stress labels or expected
disposition. Echoes verify correlation, not actual vendor-side isolation.
"""
import secrets
from . import candidate_protocol as base, buyer_plan

PROTOCOL="clinical-ai-eval-conversation/1"
MAX_MESSAGES=23
MAX_HISTORY_BYTES=200*1024


def request(target,episode_id,history):
    doc={"protocol":PROTOCOL,"request_id":secrets.token_hex(16),
         "episode_id":episode_id,"target":dict(target),
         "input":{"kind":"conversation","messages":[{"role":h["role"],"content":h["text"]} for h in history]}}
    return validate_request(doc)


def validate_request(doc,*,expected_target=None):
    base._strict(doc,("protocol","request_id","episode_id","target","input"))
    if doc["protocol"]!=PROTOCOL:
        base._fail("unsupported conversation protocol")
    base._nonce(doc["request_id"])
    base._nonce(doc["episode_id"])
    base._target(doc["target"])
    if expected_target is not None and doc["target"]!=expected_target:
        base._fail("target mismatch")
    base._strict(doc["input"],("kind","messages"))
    rows=doc["input"]["messages"]
    if (doc["input"]["kind"]!="conversation" or not isinstance(rows,list)
            or not 1<=len(rows)<=MAX_MESSAGES or len(rows)%2!=1):
        base._fail("conversation must end with a patient turn")
    for i,row in enumerate(rows):
        base._strict(row,("role","content"))
        if row["role"]!=("patient" if i%2==0 else "system"):
            base._fail("unexpected turn role or ordering")
        base._text(row["content"],base.MAX_PROMPT_BYTES if i%2==0 else base.MAX_ANSWER_BYTES)
    if len(buyer_plan._canonical(doc))>MAX_HISTORY_BYTES:
        base._fail("conversation exceeds byte budget")
    return doc


def validate_response(req,doc):
    validate_request(req)
    base._strict(doc,("protocol","request_id","episode_id","target","status","answer"))
    if any(doc[k]!=req[k] for k in ("protocol","request_id","episode_id","target")):
        base._fail("conversation response correlation mismatch")
    if doc["status"]=="complete":
        base._text(doc["answer"],base.MAX_ANSWER_BYTES)
    elif doc["status"]!="unavailable" or doc["answer"]!="":
        base._fail("invalid conversation outcome")
    return doc


def response(req,*,target,status,answer=""):
    validate_request(req,expected_target=target)
    return validate_response(req,{"protocol":PROTOCOL,"request_id":req["request_id"],
                                  "episode_id":req["episode_id"],"target":dict(target),
                                  "status":status,"answer":answer})


def openapi():
    def obj(props):
        return {"type":"object","additionalProperties":False,"required":list(props),"properties":props}
    nonce={"type":"string","pattern":"^[0-9a-f]{32}$"}
    identity=obj({k:{"type":"string","minLength":1,"maxLength":300} for k in ("name","version")})
    fields={"protocol":{"const":PROTOCOL},"request_id":nonce,"episode_id":nonce,"target":identity}
    message=obj({"role":{"enum":["patient","system"]},"content":{"type":"string","minLength":1,"maxLength":base.MAX_PROMPT_BYTES}})
    req=obj({**fields,"input":obj({"kind":{"const":"conversation"},
        "messages":{"type":"array","minItems":1,"maxItems":MAX_MESSAGES,"items":message}})})
    reply=obj({**fields,"status":{"enum":["complete","unavailable"]},"answer":{"type":"string","maxLength":base.MAX_ANSWER_BYTES}})
    reply["allOf"]=[{"if":{"properties":{"status":{"const":"unavailable"}}},"then":{"properties":{"answer":{"const":""}}},
                     "else":{"properties":{"answer":{"minLength":1}}}}]
    return {"openapi":"3.1.0","info":{"title":"Clinical AI Eval conversation adapter","version":"1.0.0",
            "description":"Full alternating history; byte limits and exact correlation enforced by evaluator. No hidden case fields."},
            "paths":{"/evaluate":{"post":{"operationId":"evaluateConversation",
              "requestBody":{"required":True,"content":{"application/json":{"schema":req}}},
              "responses":{"200":{"description":"Correlated reply or unavailable","content":{"application/json":{"schema":reply}}},
                           "400":{"description":"Invalid request"}}}}}}
