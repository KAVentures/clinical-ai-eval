"""Synthetic HL7 v2.5.1 ORU_R01 extraction readiness, NOT a conformance validator.

No live endpoints or real patient records are accepted. The candidate is asked
to return a deliberately narrow structured observation extraction. Reference
expectations are authored fixtures, not generated by a model. No clinical
treatment or diagnosis is inferred.
"""
import copy
import json
import math
import re
from pathlib import Path

from . import buyer_plan, buyer_manual as manual, buyer_agent as buyer

SCHEMA="synthetic-hl7-readiness/1"
REPORT="synthetic-hl7-readiness-report/1"
MAX_BYTES=256*1024
MAX_EVIDENCE_BYTES=1024*1024
SYSTEM="UCUM"
CODE_SYSTEM="99FIX"
LIMITATIONS=[
    "Synthetic fixed HL7 v2.5.1 ORU_R01 fixtures, not general HL7 v2 conformance validation.",
    "Tests only the explicitly defined structured extraction contract.",
    "No terminology validation, clinical interpretation, live EHR connection, or write-back.",
    "No independently established clinical validity or deployment authorization.",
    "Missing candidate output is not a successful observation extraction.",
]


def _fail(message):
    raise buyer.BuyerError(message)


def _strict(obj,keys):
    if not isinstance(obj,dict) or set(obj)!=set(keys):
        _fail("unexpected synthetic interoperability fields")


def _target(target):
    _strict(target,("name","version"))
    for value in target.values():
        if not isinstance(value,str) or not value.strip() or len(value)>300:
            _fail("exact bounded target name and version required")
    return copy.deepcopy(target)


def _obx(sub="1",*,status="F",value="12.5",unit="mg/L",code="fixture-analyte",kind="NM"):
    # OBX-3 coded observation, OBX-4 sub-ID, OBX-5 value,
    # OBX-6 units, OBX-11 result status.
    return "|".join(["OBX","1",kind,code+"^Synthetic observation^"+CODE_SYSTEM,sub,
                     str(value),unit+"^Synthetic unit^"+SYSTEM,"","","","",status])


def _message(control,patient,*orders):
    segments=["MSH|^~\\&|FIXTURE|TEST|CANDIDATE|TEST|20200101100000||ORU^R01^ORU_R01|"+control+"|T|2.5.1",
              "PID|1||"+patient+"^^^FIXTURE^PI||Synthetic^Patient"]
    for order,observations in orders:
        segments.append("OBR|1||"+order+"^FIXTURE|fixture-panel^Synthetic panel^99FIX")
        segments.extend(observations)
    return "\r".join(segments)+"\r"


def _fact(order="order-one",sub="1",value=12.5,unit="mg/L",code="fixture-analyte"):
    return {"source_id":order+":"+sub,"code_system":CODE_SYSTEM,"code":code,
            "value":value,"unit_system":SYSTEM,"unit_code":unit}


def _fixtures():
    def one(*obs,order="order-one",control="msg-one",patient="fixture-a"):
        return _message(control,patient,(order,obs))
    return [
        ("baseline",[one(_obx())],"complete",[_fact()]),
        ("patient_isolation",[one(_obx(value=99),order="other-order",control="msg-other",patient="fixture-b"),one(_obx())],
         "complete",[_fact()]),
        ("deleted_result",[one(_obx("2",status="D",value=99),_obx())],"complete",[_fact()]),
        ("preliminary_excluded",[one(_obx(status="P",value=99))],"no_eligible_observations",[]),
        ("missing_value",[one(_obx(value=""))],"no_eligible_observations",[]),
        ("zero_not_missing",[one(_obx(value=0))],"complete",[_fact(value=0)]),
        ("unit_preservation",[one(_obx(value=1.25,unit="g/L"))],"complete",[_fact(value=1.25,unit="g/L")]),
        ("nonnumeric_excluded",[one(_obx(kind="ST",value="not measured"))],"no_eligible_observations",[]),
        ("order_scope",[_message("msg-one","fixture-a",("order-one",[_obx()]),
                                  ("order-two",[_obx(value=3,code="fixture-second")]))],
         "complete",[_fact(),_fact("order-two",value=3,code="fixture-second")]),
        ("observation_order_invariance",[one(_obx("2",value=3,code="fixture-second"),_obx())],
         "complete",[_fact(),_fact(sub="2",value=3,code="fixture-second")]),
    ]


INSTRUCTION=("For the synthetic PID-3 patient identifier, process only the supplied HL7 v2.5.1 ORU_R01 messages. "
             "Return OBX observations with status F and value type NM and a present numeric OBX-5. "
             "Use source_id = OBR-3 first component + ':' + OBX-4; preserve OBX-3 code and coding system, "
             "OBX-5 numeric value and OBX-6 unit code and coding system. No unit conversion or inference. "
             "Exclude other patients, deleted/preliminary results, missing and nonnumeric values. "
             "Use no_eligible_observations when none match; unavailable when processing fails. "
             "This fixed exercise does not model message update/correction semantics.")


def build(target):
    target=_target(target)
    rows=[]
    for name,messages,status,facts in _fixtures():
        body={"patient_id":"fixture-a","messages":messages}
        rows.append({"probe":name,"slot":buyer_plan._digest([SCHEMA,name,body])[:32],
                     **body,"expected_status":status,"expected_facts":facts})
    doc={"schema":SCHEMA,"hl7_version":"2.5.1","target":target,"synthetic":True,
         "instruction":INSTRUCTION,"rows":rows,"decision_grade":False,"limitations":LIMITATIONS[:]}
    return {**doc,"digest":buyer_plan._digest(doc)}


def exchange(plan):
    _verify_plan(plan)
    return {"schema":"synthetic-hl7-exchange/1","target":copy.deepcopy(plan["target"]),"synthetic":True,
            "plan_digest":plan["digest"],"instruction":plan["instruction"],
            "probes":[{k:copy.deepcopy(r[k]) for k in ("slot","patient_id","messages")} for r in plan["rows"]]}


def template(plan):
    _verify_plan(plan)
    return {"schema":"synthetic-hl7-responses/1","target":copy.deepcopy(plan["target"]),"synthetic":True,
            "plan_digest":plan["digest"],"responses":[{"slot":r["slot"],"status":"unavailable","facts":[]} for r in plan["rows"]]}


def _verify_plan(plan):
    if not isinstance(plan,dict) or buyer_plan._canonical(plan)!=buyer_plan._canonical(build(plan["target"])):
        _fail("fixture plan differs from pinned synthetic definitions")


def _facts(values):
    if not isinstance(values,list) or len(values)>32:
        _fail("bounded structured extraction required")
    normalized={}
    for fact in values:
        _strict(fact,("source_id","code_system","code","value","unit_system","unit_code"))
        for k in ("source_id","code_system","code","unit_system","unit_code"):
            if not isinstance(fact[k],str) or not re.fullmatch(r"[A-Za-z0-9._:/%+@~#()\[\]{}*-]{1,200}",fact[k]):
                _fail("invalid structured observation field")
        n=fact["value"]
        if type(n) not in (int,float) or abs(n)>1e12 or not math.isfinite(n):
            _fail("finite bounded numerical observation required")
        key=fact["source_id"]
        if key in normalized:
            _fail("duplicate observation source")
        normalized[key]=fact
    return normalized


def assess(plan,responses):
    _verify_plan(plan)
    _strict(responses,("schema","target","synthetic","plan_digest","responses"))
    if (responses["schema"]!="synthetic-hl7-responses/1" or responses["synthetic"] is not True or
            responses["target"]!=plan["target"] or responses["plan_digest"]!=plan["digest"]):
        _fail("response does not bind exact synthetic target and fixtures")
    values=responses["responses"]
    if not isinstance(values,list) or len(values)!=len(plan["rows"]):
        _fail("complete response inventory required, mark unavailable explicitly")
    byslot={}
    for row in values:
        _strict(row,("slot","status","facts"))
        if not isinstance(row["slot"],str) or row["slot"] in byslot or row["status"] not in ("complete","no_eligible_observations","unavailable"):
            _fail("invalid or duplicate response slot")
        facts=_facts(row["facts"])
        if row["status"]!="complete" and facts:
            _fail("unavailable or empty status cannot carry observations")
        byslot[row["slot"]]=(row["status"],facts)
    if set(byslot)!={r["slot"] for r in plan["rows"]}:
        _fail("response inventory differs from exact probes")
    results=[]
    for probe in plan["rows"]:
        status,facts=byslot[probe["slot"]]
        expected=_facts(probe["expected_facts"])
        if status=="unavailable":
            results.append({"probe":probe["probe"],"status":"unavailable","missing":None,
                            "unexpected":None,"changed":None,"status_matches":None})
            continue
        missing=sorted(set(expected)-set(facts))
        unexpected=sorted(set(facts)-set(expected))
        changed=sorted(k for k in set(expected)&set(facts) if facts[k]!=expected[k])
        matches=status==probe["expected_status"]
        results.append({"probe":probe["probe"],"status":"exact_match" if matches and not (missing or unexpected or changed) else "mismatch",
                        "missing":missing,"unexpected":unexpected,"changed":changed,"status_matches":matches})
    report={"schema":REPORT,"plan_digest":plan["digest"],"target":plan["target"],
            "response_digest":buyer_plan._digest(responses),"synthetic":True,"rows":results,
            "summary":{"planned":len(results),**{s:sum(r["status"]==s for r in results)
                        for s in ("exact_match","mismatch","unavailable")}},
            "decision_grade":False,"deployment_authorized":False,"limitations":LIMITATIONS[:]}
    return {**report,"digest":buyer_plan._digest(report)}


def package(plan,responses):
    report=assess(plan,responses)
    doc={"schema":"synthetic-hl7-evidence/1","plan":plan,"responses":responses,"report":report,
         "decision_grade":False}
    return {**doc,"digest":buyer_plan._digest(doc)}


def verify(doc,expected_digest=None):
    _strict(doc,("schema","plan","responses","report","decision_grade","digest"))
    if buyer_plan._canonical(doc)!=buyer_plan._canonical(package(doc["plan"],doc["responses"])) or (expected_digest is not None and doc["digest"]!=expected_digest):
        _fail("synthetic HL7 v2 evidence differs from deterministic replay or expected digest")
    return {"status":"REPLAY_VERIFIED","digest":doc["digest"],"summary":doc["report"]["summary"],
            "expected_digest_matched":expected_digest is not None,"decision_grade":False,
            "deployment_authorized":False}


def parse(raw,*,evidence=False):
    if len(raw)>(MAX_EVIDENCE_BYTES if evidence else MAX_BYTES):
        _fail("synthetic HL7 v2 input exceeds size limit")
    return manual._parse(raw)


def read(path,*,evidence=False):
    p=Path(path)
    if p.is_symlink() or not p.is_file():
        _fail("regular local JSON file required")
    with p.open("rb") as f:
        limit=MAX_EVIDENCE_BYTES if evidence else MAX_BYTES
        return parse(f.read(limit+1),evidence=evidence)


def cli(args):
    try:
        if args.action=="prepare":
            plan=build({"name":args.target_name,"version":args.target_version})
            result={"plan":plan,"exchange":exchange(plan),"response_template":template(plan)}
        elif args.action=="assess":
            result=package(read(args.plan),read(args.responses))
        else:
            result=verify(read(args.evidence,evidence=True),args.expected_digest)
        print(json.dumps({"ok":True,"result":result},ensure_ascii=False,allow_nan=False))
    except (OSError,ValueError,RuntimeError,KeyError,TypeError,AttributeError,OverflowError):
        print(json.dumps({"ok":False,"error":"synthetic HL7 v2 readiness operation refused","decision_grade":False}))
        raise SystemExit(1)
